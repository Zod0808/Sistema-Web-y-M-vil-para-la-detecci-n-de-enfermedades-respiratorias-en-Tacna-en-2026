#!/usr/bin/env node

/**
 * Script para configurar automáticamente la ubicación del Android SDK
 */

const fs = require('fs');
const path = require('path');
const os = require('os');

const ANDROID_DIR = path.join(__dirname, '..', 'android');
const LOCAL_PROPERTIES = path.join(ANDROID_DIR, 'local.properties');

function findAndroidSDK() {
  const homeDir = os.homedir();
  const platform = os.platform();
  
  // Rutas comunes del Android SDK
  const commonPaths = [
    // Windows
    path.join(homeDir, 'AppData', 'Local', 'Android', 'Sdk'),
    path.join(process.env.LOCALAPPDATA || '', 'Android', 'Sdk'),
    path.join(process.env.PROGRAMFILES || '', 'Android', 'android-sdk'),
    path.join('C:', 'Users', os.userInfo().username, 'AppData', 'Local', 'Android', 'Sdk'),
    
    // Linux/Mac
    path.join(homeDir, 'Android', 'Sdk'),
    path.join(homeDir, 'Library', 'Android', 'sdk'),
    path.join(homeDir, '.android', 'sdk'),
    
    // Variable de entorno
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
  ].filter(Boolean);

  // Verificar cada ruta
  for (const sdkPath of commonPaths) {
    if (sdkPath && fs.existsSync(sdkPath)) {
      // Verificar que tenga la estructura típica del SDK
      const platformsPath = path.join(sdkPath, 'platforms');
      const buildToolsPath = path.join(sdkPath, 'build-tools');
      
      if (fs.existsSync(sdkPath) && (fs.existsSync(platformsPath) || fs.existsSync(buildToolsPath))) {
        return sdkPath;
      }
    }
  }

  return null;
}

function createLocalProperties(sdkPath) {
  const content = `## This file is automatically generated by Android Studio.
# Do not modify this file -- YOUR CHANGES WILL BE ERASED!
#
# This file should *NOT* be checked into Version Control Systems,
# as it contains information specific to your local configuration.
#
# Location of the SDK. This is only used by Gradle.
# For customization when using a Version Control System, please read the
# header note.
sdk.dir=${sdkPath.replace(/\\/g, '/')}
`;

  fs.writeFileSync(LOCAL_PROPERTIES, content, 'utf8');
  console.log(`✅ Archivo local.properties creado con SDK: ${sdkPath}`);
}

function main() {
  console.log('🔍 Buscando Android SDK...\n');

  // Verificar si ya existe local.properties
  if (fs.existsSync(LOCAL_PROPERTIES)) {
    const existing = fs.readFileSync(LOCAL_PROPERTIES, 'utf8');
    const sdkMatch = existing.match(/sdk\.dir=(.+)/);
    if (sdkMatch) {
      const existingPath = sdkMatch[1].trim();
      if (fs.existsSync(existingPath)) {
        console.log(`✅ Android SDK ya configurado: ${existingPath}\n`);
        return;
      } else {
        console.log(`⚠️  SDK configurado no existe: ${existingPath}`);
        console.log('   Buscando nueva ubicación...\n');
      }
    }
  }

  // Buscar SDK
  const sdkPath = findAndroidSDK();

  if (!sdkPath) {
    console.error('❌ No se pudo encontrar el Android SDK automáticamente.\n');
    console.log('📋 Opciones para solucionar:\n');
    console.log('1. Instalar Android Studio:');
    console.log('   https://developer.android.com/studio\n');
    console.log('2. Configurar manualmente:');
    console.log('   Crea el archivo android/local.properties con:');
    console.log('   sdk.dir=C:/Users/TU_USUARIO/AppData/Local/Android/Sdk\n');
    console.log('3. Configurar variable de entorno ANDROID_HOME:');
    console.log('   - Abre "Variables de entorno" en Windows');
    console.log('   - Agrega ANDROID_HOME con la ruta del SDK\n');
    console.log('4. Si tienes Android Studio instalado:');
    console.log('   - Abre Android Studio');
    console.log('   - Ve a File > Settings > Appearance & Behavior > System Settings > Android SDK');
    console.log('   - Copia la ruta "Android SDK Location"\n');
    
    // Crear archivo de ejemplo
    const examplePath = path.join(ANDROID_DIR, 'local.properties.example');
    if (!fs.existsSync(examplePath)) {
      const exampleContent = `## Ejemplo de local.properties
# Reemplaza la ruta con la ubicación real de tu Android SDK
sdk.dir=C:/Users/TU_USUARIO/AppData/Local/Android/Sdk
`;
      fs.writeFileSync(examplePath, exampleContent, 'utf8');
      console.log(`\n📝 Se creó un archivo de ejemplo en: ${examplePath}`);
    }
    
    process.exit(1);
  }

  // Crear local.properties
  createLocalProperties(sdkPath);
  console.log('\n✅ Configuración completada. Ahora puedes ejecutar: npm run apk\n');
}

main();

